export function enrichRigorousTopic(topic: Topic): Topic {
  const topicPatches = patches[topic.id];
  if (!topicPatches) return topic;

  return {
    ...topic,
    blocks: topic.blocks.map((block) => {
      const patch = topicPatches[block.title];
      return patch ? { ...block, ...patch } : block;
    }),
  };
}

export const rigorousTopicPatches = patches;
