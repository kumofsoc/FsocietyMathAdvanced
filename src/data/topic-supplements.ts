function applySupplement(topic: Topic, supplement: TopicSupplement): Topic {
  const blocks = [...topic.blocks];
  const marker = supplement.insertAfterTitleIncludes
    ? blocks.findIndex((block) => block.title.includes(supplement.insertAfterTitleIncludes!))
    : -1;

  const insertAt = marker >= 0 ? marker + 1 : blocks.length;
  blocks.splice(insertAt, 0, ...supplement.blocks);

  return { ...topic, blocks };
}

export function composeTopicWithSupplements(topic: Topic): Topic {
  return supplements
    .filter((supplement) => supplement.topicId === topic.id)
    .reduce(applySupplement, topic);
}

